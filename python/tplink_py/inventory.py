"""Read-only AX23 inventory generator for existing OpenTofu configurations.

Writes inventory.auto.tfvars and imports.tf after one complete router read.
Both generated files contain private LAN inventory and must stay gitignored.
"""
import argparse
import json
import os
from pathlib import Path
import re
import tempfile

from tplinkrouterc6u import TplinkRouterSG


def hcl_string(value: str) -> str:
    """Quote a string without allowing Terraform template interpolation."""
    return json.dumps(str(value), ensure_ascii=False).replace("\${", "$\${").replace("%{", "%%{")


def canonical_mac(value: str) -> str:
    raw = re.sub(r"[-:.]", "", str(value))
    if not re.fullmatch(r"[0-9a-fA-F]{12}", raw):
        raise ValueError(f"Invalid router MAC address: {value!r}")
    raw = raw.upper()
    return "-".join(raw[i:i + 2] for i in range(0, 12, 2))


def inventory_rows(reservations, forwards):
    """Verify identities before rendering. Never adopt ambiguous router rows."""
    dhcp = {}
    rules = {}
    for row in reservations:
        mac = canonical_mac(row.macaddr)
        if mac in dhcp:
            raise ValueError(f"Duplicate reservation MAC: {mac}")
        dhcp[mac] = {
            "ip": str(row.ipaddr),
            "hostname": str(row.hostname or ""),
            "enabled": bool(row.enabled),
        }
    for row in forwards:
        name = str(row.name)
        if not name or name in rules:
            raise ValueError(f"Empty or duplicate port-forward name: {name!r}")
        rules[name] = {
            "ip": str(row.ipaddr),
            "external_port": str(row.external_port),
            "internal_port": str(row.internal_port),
            "protocol": str(row.protocol),
            "enabled": bool(row.enabled),
        }
    return dict(sorted(dhcp.items())), dict(sorted(rules.items()))


def render_tfvars(firmware, dhcp, rules):
    model = f"{firmware.model} {firmware.hardware_version}".strip()
    lines = [
        "# Generated by terraform-provider-tplink (python -m tplink_py.inventory).",
        "# Contains private LAN device inventory. Do not commit.",
        f"# router at generation time: {model} {firmware.firmware_version}",
        "",
        "dhcp_reservations = {",
    ]
    for mac, row in dhcp.items():
        lines.append(
            f'  {hcl_string(mac)} = {{ ip = {hcl_string(row["ip"])}, '
            f'hostname = {hcl_string(row["hostname"])}, '
            f'enabled = {str(row["enabled"]).lower()} }}'
        )
    lines.extend(["}", "", "port_forwards = {"])
    for name, row in rules.items():
        lines.append(
            f'  {hcl_string(name)} = {{ ip = {hcl_string(row["ip"])}, '
            f'external_port = {hcl_string(row["external_port"])}, '
            f'internal_port = {hcl_string(row["internal_port"])}, '
            f'protocol = {hcl_string(row["protocol"])}, '
            f'enabled = {str(row["enabled"]).lower()} }}'
        )
    return "\n".join(lines + ["}", ""])


def render_imports(dhcp, rules):
    lines = [
        "# Generated by terraform-provider-tplink (python -m tplink_py.inventory).",
        "# Import CURRENT router rows into state. Contains private LAN inventory.",
        "# Regenerate only after reviewing deliberate out-of-band changes.",
        "",
    ]
    for mac in dhcp:
        lines.extend([
            "import {",
            f"  to = tplink_dhcp_reservation.entries[{hcl_string(mac)}]",
            f"  id = {hcl_string(mac)}",
            "}",
            "",
        ])
    for name in rules:
        lines.extend([
            "import {",
            f"  to = tplink_port_forward.rules[{hcl_string(name)}]",
            f"  id = {hcl_string(name)}",
            "}",
            "",
        ])
    return "\n".join(lines)


def write_private(path: Path, content: str) -> None:
    """Write with restrictive permissions, replacing via same-directory rename."""
    with tempfile.NamedTemporaryFile(
        mode="w", encoding="utf-8", dir=path.parent,
        prefix=f".{path.name}.", delete=False,
    ) as file:
        temp = Path(file.name)
        os.chmod(temp, 0o600)
        try:
            file.write(content)
            file.flush()
            os.fsync(file.fileno())
        except BaseException:
            temp.unlink(missing_ok=True)
            raise
    os.replace(temp, path)


def read_router(host, password, timeout, password_key_pin=None, auth_key_pin=None):
    kwargs = {}
    if password_key_pin:
        kwargs["password_key_pin"] = password_key_pin
    if auth_key_pin:
        kwargs["auth_key_pin"] = auth_key_pin
    router = TplinkRouterSG(host, password, timeout=timeout, **kwargs)
    router.authorize()
    try:
        firmware = router.get_firmware()
        dhcp, rules = inventory_rows(
            router.get_ipv4_reservations(), router.get_ipv4_port_forwards()
        )
        return firmware, dhcp, rules
    finally:
        router.logout()


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dir", type=Path, default=Path("."))
    parser.add_argument("--host", default=os.getenv("TPLINK_HOST", "http://192.168.0.1"))
    parser.add_argument("--timeout", type=int, default=30)
    parser.add_argument("--dry-run", action="store_true", help="Read and validate, but do not write files")
    args = parser.parse_args(argv)
    if args.timeout <= 0:
        parser.error("--timeout must be positive")
    password = os.getenv("TPLINK_PASSWORD")
    if not password:
        parser.error("set TPLINK_PASSWORD (never provide a password on the command line)")

    firmware, dhcp, rules = read_router(
        args.host, password, args.timeout,
        password_key_pin=os.getenv("TPLINK_PASSWORD_KEY_PIN"),
        auth_key_pin=os.getenv("TPLINK_AUTH_KEY_PIN"),
    )
    tfvars = render_tfvars(firmware, dhcp, rules)
    imports = render_imports(dhcp, rules)
    if args.dry_run:
        print(f"read-only inventory check: {len(dhcp)} reservations, {len(rules)} forwards")
        return
    args.dir.mkdir(parents=True, exist_ok=True, mode=0o700)
    write_private(args.dir / "inventory.auto.tfvars", tfvars)
    write_private(args.dir / "imports.tf", imports)
    print(f"wrote inventory.auto.tfvars and imports.tf ({len(dhcp)} reservations, {len(rules)} forwards)")


if __name__ == "__main__":
    main()
