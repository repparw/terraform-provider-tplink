// Command tfinventory emits OpenTofu variable and import files for the
// router's current configuration, so the existing resources can be adopted
// into state without changing the router.
//
// It performs one login, read-only queries, and a logout, then writes:
//
//   - inventory.auto.tfvars  (variable values; contains MACs and hostnames)
//   - imports.tf             (import blocks referencing the variable keys)
//
// Both files contain the LAN's device inventory: keep them out of git (the
// infra/router/.gitignore in repparw/nix already excludes them).
//
// Usage: go run ./cmd/tfinventory -dir /path/to/infra/router
// Environment: TPLINK_HOST (default http://192.168.0.1), TPLINK_PASSWORD.
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/repparw/terraform-provider-tplink/internal/client"
)

func main() {
	dir := flag.String("dir", ".", "target OpenTofu root (infra/router)")
	host := flag.String("host", "", "router address (default TPLINK_HOST or http://192.168.0.1)")
	flag.Parse()

	password := os.Getenv("TPLINK_PASSWORD")
	if password == "" {
		fmt.Fprintln(os.Stderr, "TPLINK_PASSWORD not set")
		os.Exit(2)
	}
	target := *host
	if target == "" {
		target = os.Getenv("TPLINK_HOST")
	}
	if target == "" {
		target = "http://192.168.0.1"
	}

	cl, err := client.New(client.Config{Host: target, Password: password, TLSSkipVerify: true})
	if err != nil {
		fail(err)
	}

	var reservations []client.DHCPReservation
	var forwards []client.PortForward
	var fw *client.Firmware
	if err := withReads(cl, func() error {
		// Keep firmware and inventory reads in the same authenticated session.
		// A second login evicts the first on this router.
		fw, _ = cl.GetFirmware()
		var err error
		if reservations, err = cl.GetDHCPReservations(); err != nil {
			return err
		}
		if forwards, err = cl.GetPortForwards(); err != nil {
			return err
		}
		return nil
	}); err != nil {
		fail(err)
	}

	tfvars := renderTFVars(fw, reservations, forwards)
	imports := renderImports(reservations, forwards)

	if err := os.MkdirAll(*dir, 0o700); err != nil {
		fail(err)
	}
	varsPath := filepath.Join(*dir, "inventory.auto.tfvars")
	importsPath := filepath.Join(*dir, "imports.tf")
	if err := os.WriteFile(varsPath, []byte(tfvars), 0o600); err != nil {
		fail(err)
	}
	if err := os.WriteFile(importsPath, []byte(imports), 0o600); err != nil {
		fail(err)
	}
	fmt.Printf("wrote %s (%d reservations, %d port forwards)\n", varsPath,
		len(reservations), len(forwards))
	fmt.Printf("wrote %s\n", importsPath)
	fmt.Println("next: tofu init -plugin-dir=... && tofu plan  # expect imports only, no changes")
}

// withReads runs fn inside a single authorized session and logs out.
func withReads(cl *client.Client, fn func() error) error {
	if err := cl.Authorize(); err != nil {
		return err
	}
	err := fn()
	_ = cl.Logout()
	return err
}

func renderTFVars(fw *client.Firmware, reservations []client.DHCPReservation,
	forwards []client.PortForward) string {
	var b strings.Builder
	fmt.Fprintln(&b, "# Generated by terraform-provider-tplink cmd/tfinventory.")
	fmt.Fprintln(&b, "# Contains the LAN device inventory: gitignored, do not commit.")
	fmt.Fprintln(&b, "# key = MAC (dash-uppercase) for reservations, rule name for forwards.")
	fmt.Fprintf(&b, "# router at generation time: %s %s\n\n",
		fwModel(fw), fwVersion(fw))
	fmt.Fprintln(&b, "dhcp_reservations = {")
	for _, r := range reservations {
		fmt.Fprintf(&b, "  %s = { ip = %s, hostname = %s, enabled = %t }\n",
			tfQuote(tfKey(r.MAC)), tfQuote(r.IP), tfQuote(r.Hostname), r.Enabled)
	}
	fmt.Fprintln(&b, "}")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "port_forwards = {")
	for _, f := range forwards {
		fmt.Fprintf(&b, "  %s = { ip = %s, external_port = %s, internal_port = %s, protocol = %s, enabled = %t }\n",
			tfQuote(tfKey(f.Name)), tfQuote(f.IP), tfQuote(f.ExternalPort), tfQuote(f.InternalPort), tfQuote(f.Protocol), f.Enabled)
	}
	fmt.Fprintln(&b, "}")
	return b.String()
}

func renderImports(reservations []client.DHCPReservation, forwards []client.PortForward) string {
	var b strings.Builder
	fmt.Fprintln(&b, "# Generated by terraform-provider-tplink cmd/tfinventory.")
	fmt.Fprintln(&b, "# Adopt the CURRENT router rows into state. Inert once applied;")
	fmt.Fprintln(&b, "# regenerate after deliberate out-of-band changes. Gitignored:")
	fmt.Fprintln(&b, "# addresses contain the LAN device inventory.")
	fmt.Fprintln(&b)
	for _, r := range reservations {
		fmt.Fprintf(&b, "import {\n  to = tplink_dhcp_reservation.entries[%s]\n  id = %s\n}\n\n",
			tfQuote(tfKey(r.MAC)), tfQuote(r.MAC))
	}
	for _, f := range forwards {
		fmt.Fprintf(&b, "import {\n  to = tplink_port_forward.rules[%s]\n  id = %s\n}\n\n",
			tfQuote(tfKey(f.Name)), tfQuote(f.Name))
	}
	return b.String()
}

// tfKey preserves exact router identity for map keys.
func tfKey(s string) string { return s }

// Terraform quoted templates interpolate ${...} and interpret %{...};
// escaping is necessary even inside quoted strings generated by Go's %q.
func tfQuote(s string) string {
	return strings.ReplaceAll(
		strings.ReplaceAll(strconv.Quote(s), "${", "$${"),
		"%{", "%%{",
	)
}

func fwModel(fw *client.Firmware) string {
	if fw == nil {
		return "(unavailable)"
	}
	return strings.TrimSpace(fw.Model + " " + fw.HardwareVersion)
}

func fwVersion(fw *client.Firmware) string {
	if fw == nil {
		return "(unavailable)"
	}
	return fw.FirmwareVersion
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "ERROR:", err)
	os.Exit(1)
}
